"""gfxstream の Vulkan プロトコル（ホストのデコーダーとゲストのエンコーダー）を生成する。

上流の external/mesa3d/src/gfxstream/codegen/generate-gfxstream-vulkan.sh と同じ手順を
Windows の Python で実行する。既定では一時ディレクトリへ出力し、リポジトリにある生成物と
比較する（--apply で上書きする）。

  ホスト: genvk.py -registry <gfxstream>/third_party/vulkan_docs/xml/vk.xml
                   -registryGfxstream <mesa>/src/gfxstream/codegen/xml/vk_gfxstream.xml cereal
  ゲスト: CEREAL_VARIANT=guest、-registry <mesa>/src/vulkan/registry/vk.xml

例:
  python -m scripts.guest.gfxstream_codegen            # 生成して差分を表示（書き込まない）
  python -m scripts.guest.gfxstream_codegen --apply    # ホスト・ゲストの生成物を更新する
"""
from __future__ import annotations

import argparse
import filecmp
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
AOSP = ROOT / "third_party/aosp/emu-main-win"


def run_genvk(mesa: Path, registry: Path, out: Path, env: dict, extra: list[str]) -> None:
    genvk = mesa / "src/gfxstream/codegen/scripts/genvk.py"
    custom = mesa / "src/gfxstream/codegen/xml/vk_gfxstream.xml"
    cmd = [sys.executable, str(genvk), "-registry", str(registry), "-registryGfxstream", str(custom),
           *extra, "-o", str(out)]
    p = subprocess.run(cmd, cwd=genvk.parent, env=env, capture_output=True, text=True)
    if p.returncode != 0:
        sys.stderr.write(p.stdout[-3000:] + p.stderr[-3000:])
        raise SystemExit(f"genvk が失敗: {' '.join(cmd)}")
    # 新しいコマンドのオペコードは stderr に「既知のオペコード」として出る
    for line in p.stderr.splitlines():
        if re.match(r'\s+"vk\w+": \d+,', line):
            print("新規オペコード:", line.strip())


def compare(generated: Path, checked_in: Path, apply: bool) -> list[str]:
    changed = []
    for f in sorted(generated.rglob("*")):
        if not f.is_file():
            continue
        rel = f.relative_to(generated)
        dst = checked_in / rel
        if f.name == ".clang-format":
            continue
        if dst.exists() and filecmp.cmp(f, dst, shallow=False):
            continue
        # 改行コードだけの違いは無視する
        if dst.exists() and f.read_bytes().replace(b"\r\n", b"\n") == dst.read_bytes().replace(b"\r\n", b"\n"):
            continue
        changed.append(str(rel))
        if apply:
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(f, dst)
    return changed


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--mesa", type=Path, default=AOSP / "external/mesa3d")
    ap.add_argument("--gfxstream", type=Path, default=AOSP / "hardware/google/gfxstream")
    ap.add_argument("--apply", action="store_true", help="生成物をソースツリーへ書き込む")
    ap.add_argument("--keep", type=Path, help="生成物を残すディレクトリ（差分の確認用）")
    ap.add_argument("--clang-format-dir", type=Path,
                    default=ROOT / ".velox/sdk-toolchain/ndk/30.0.16248370/toolchains/llvm/prebuilt/windows-x86_64/bin")
    args = ap.parse_args()
    mesa, gfx = args.mesa.resolve(), args.gfxstream.resolve()

    import contextlib
    keep = args.keep
    ctx = contextlib.nullcontext(str(keep)) if keep else tempfile.TemporaryDirectory(prefix="vx-codegen-")
    with ctx as tmp:
        tmp = Path(tmp)
        if keep and tmp.exists():
            shutil.rmtree(tmp)
        tmp.mkdir(parents=True, exist_ok=True)
        host_dir, guest_dir, scratch = tmp / "host", tmp / "guest", tmp / "scratch"
        scripts_dir = tmp / "scripts"
        for d in (host_dir / "cereal", guest_dir, scratch, scripts_dir):
            d.mkdir(parents=True)
        # 生成器は出力先のサブディレクトリを作らないので、既存のツリーと同じ構成を用意する
        for src, dst in ((gfx / "host/vulkan", host_dir),
                         (mesa / "src/gfxstream/guest/vulkan_enc/autogenerated", guest_dir),
                         (gfx / "scripts", scripts_dir), (gfx / "scripts", scratch)):
            for sub in src.rglob("*"):
                if sub.is_dir():
                    (dst / sub.relative_to(src)).mkdir(parents=True, exist_ok=True)
        # 上流と同じく生成物を clang-format（--style=file）で整える。一時ディレクトリにも
        # 各ツリーの .clang-format を置く。
        shutil.copyfile(gfx / ".clang-format", tmp / "host" / ".clang-format")
        shutil.copyfile(gfx / ".clang-format", tmp / "scripts" / ".clang-format")
        shutil.copyfile(mesa / "src/gfxstream/.clang-format", tmp / "guest" / ".clang-format")
        shutil.copyfile(gfx / ".clang-format", tmp / ".clang-format")
        base_env = dict(os.environ)
        base_env["PATH"] = str(args.clang_format_dir) + os.pathsep + base_env.get("PATH", "")

        env = dict(base_env, GFXSTREAM_HOST_DECODER_DIR=str(host_dir),
                   GFXSTREAM_OUTPUT_DIR=str(host_dir / "cereal"), GFXSTREAM_SCRIPTS_DIR=str(scripts_dir),
                   GFXSTREAM_GUEST_ENCODER_DIR=str(scratch))
        run_genvk(mesa, gfx / "third_party/vulkan_docs/xml/vk.xml", host_dir / "cereal", env, ["cereal"])

        env = dict(base_env, CEREAL_VARIANT="guest", GFXSTREAM_GUEST_ENCODER_DIR=str(guest_dir),
                   GFXSTREAM_HOST_DECODER_DIR=str(scratch), GFXSTREAM_SCRIPTS_DIR=str(scratch))
        run_genvk(mesa, mesa / "src/vulkan/registry/vk.xml", scratch, env, ["cereal"])

        # vulkan_gfxstream.h（gfxstream 独自コマンドの宣言）はホストとゲストに同じものを置く
        hdr_dir = tmp / "header"
        hdr_dir.mkdir(exist_ok=True)
        shutil.copyfile(gfx / ".clang-format", hdr_dir / ".clang-format")
        genvk = mesa / "src/gfxstream/codegen/scripts/genvk.py"
        p = subprocess.run([sys.executable, str(genvk), "-registry",
                            str(mesa / "src/gfxstream/codegen/xml/vk_gfxstream.xml"), "vulkan_gfxstream.h",
                            "-o", str(hdr_dir)], cwd=genvk.parent, env=base_env, capture_output=True, text=True)
        if p.returncode != 0:
            sys.stderr.write(p.stdout[-2000:] + p.stderr[-2000:])
            raise SystemExit("vulkan_gfxstream.h の生成に失敗")
        shutil.copyfile(hdr_dir / "vulkan_gfxstream.h", host_dir / "vulkan_gfxstream.h")
        shutil.copyfile(hdr_dir / "vulkan_gfxstream.h", guest_dir / "vulkan_gfxstream.h")

        host_changed = compare(host_dir, gfx / "host/vulkan", args.apply)
        guest_changed = compare(guest_dir, mesa / "src/gfxstream/guest/vulkan_enc/autogenerated", args.apply)
        host_changed += ["scripts/" + c for c in compare(scripts_dir, gfx / "scripts", args.apply)]
        verb = "更新" if args.apply else "差分あり"
        print(f"ホスト（{gfx / 'host/vulkan'}）: {verb} {len(host_changed)} 件")
        for c in host_changed:
            print("  ", c)
        print(f"ゲスト（{mesa / 'src/gfxstream/guest/vulkan_enc/autogenerated'}）: {verb} {len(guest_changed)} 件")
        for c in guest_changed:
            print("  ", c)
    return 0


if __name__ == "__main__":
    sys.exit(main())
